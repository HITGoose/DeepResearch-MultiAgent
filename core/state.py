"""
LangGraph State Definition

This is the central data structure that flows between all agents.
Key design principle: only pass compressed summaries, never raw content.
"""
from __future__ import annotations
from typing import TypedDict, Annotated
from pydantic import BaseModel, Field


# ===== Sub-structures =====

class SubQuery(BaseModel):
    """A single sub-query decomposed from the user's question."""
    query: str = Field(description="The search query text")
    intent: str = Field(description="What this sub-query aims to find")
    source: str = Field(default="web", description="Preferred source: web, arxiv, wiki")


class CandidatePlan(BaseModel):
    """A candidate search plan generated by the Planner."""
    plan_id: int = Field(description="Plan identifier")
    strategy: str = Field(description="High-level strategy description")
    sub_queries: list[SubQuery] = Field(description="List of sub-queries")
    coverage_score: float = Field(default=0.0, description="Simulated coverage score 0-1")
    reasoning: str = Field(default="", description="Why this plan was scored this way")


class SearchResult(BaseModel):
    """Compressed search result (NOT raw content)."""
    query: str = Field(description="The query that produced this result")
    source_type: str = Field(description="web, arxiv, or wiki")
    title: str = Field(description="Title of the source")
    url: str = Field(default="", description="Source URL")
    summary: str = Field(description="Compressed summary of key findings")
    key_claims: list[str] = Field(default_factory=list, description="Extracted atomic claims")


class ClaimVerification(BaseModel):
    """Result of cross-source verification for a single claim."""
    claim: str = Field(description="The claim being verified")
    confidence: str = Field(description="high, disputed, or unverified")
    supporting_sources: list[str] = Field(default_factory=list, description="URLs that support")
    contradicting_sources: list[str] = Field(default_factory=list, description="URLs that contradict")
    resolution: str = Field(default="", description="How the conflict was resolved, if any")


class CriticFeedback(BaseModel):
    """Feedback from the Critic agent."""
    score: float = Field(description="Overall quality score 0-10")
    completeness: float = Field(description="Coverage of user query 0-10")
    accuracy: float = Field(description="Factual accuracy assessment 0-10")
    coherence: float = Field(description="Report structure and flow 0-10")
    missing_aspects: list[str] = Field(default_factory=list, description="What's missing")
    suggestions: str = Field(default="", description="Improvement suggestions")
    verdict: str = Field(description="pass or refine")


# ===== Reducers =====

def merge_search_results(existing: list[SearchResult] | None, update: list[SearchResult] | None) -> list[SearchResult]:
    """
    追加型 reducer，节点返回 None 时清空。

    原来用 operator.add：prepare_iteration 返回 [] 只会得到"旧值 + []"，
    结果跨轮累积，Analyzer / Writer 只能靠截取最近几条补救。
    """
    if update is None:
        return []
    return (existing or []) + update


# ===== Main State =====

class ResearchState(TypedDict):
    """
    The global state passed between agents in the LangGraph workflow.
    
    Design principles:
    1. Only compressed summaries, never raw content
    2. Each agent reads what it needs, writes what downstream needs
    3. Iteration history is compressed, not accumulated
    """
    # --- Input ---
    user_query: str                                    # Original user question

    # --- Planner outputs ---
    candidate_plans: list[CandidatePlan]               # Simulate-Before-Act: all candidates
    selected_plan: CandidatePlan | None                # The chosen plan
    
    # --- Searcher outputs ---
    search_results: Annotated[list[SearchResult], merge_search_results]  # 本轮搜索结果，返回 None 清空
    
    # --- Analyzer outputs ---
    verified_claims: list[ClaimVerification]            # Cross-source verification results
    analysis_summary: str                              # Compressed analysis for Writer
    
    # --- Writer outputs ---
    report_draft: str                                  # Current report draft
    citations: list[dict]                              # Citation tracking: [{claim, source_url}]
    
    # --- Critic outputs ---
    critic_feedback: CriticFeedback | None             # Latest feedback
    
    # --- Control flow ---
    current_iteration: int                             # Current refinement iteration (0-indexed)
    failed_strategies: list[str]                       # Strategies to avoid in re-planning
    status: str                                        # planning, searching, analyzing, writing, critiquing, done
